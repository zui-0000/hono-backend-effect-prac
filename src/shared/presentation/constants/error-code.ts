/**
 * API のエラーコード体系。
 * `<HTTP ステータス><連番>` の 4 桁で、下 1 桁 0 が各ステータスの汎用エラー、
 * 1 以降が具体的な事由を表す専用エラー。
 *
 * **ここが値の登録簿。** TypeSpec 側の `ErrorCode` は `scalar ... extends string` で、
 * 値そのものは列挙していない（各エラーモデルの `@example` に現れるだけ）。
 *
 * **専用コードを足すのは「クライアントが分岐する必要のある事由」だけ。**
 * 4091 (メールアドレス重複) は、画面に「別のアドレスを入れて」と出すために
 * 汎用の 409 と区別が要る。一方、経路の打ち間違いのように**誰も分岐しないもの**は
 * 汎用のまま返す。コードを増やすと契約の周知とクライアント実装の手間が乗るので、
 * 増やす側に理由が要る。
 */
export const ErrorCode = {
  /** 400 リクエスト内容が不正 (汎用) */
  BadRequest: "4000",
  /** 401 認証情報が不正 (汎用) */
  Unauthorized: "4010",
  /** 404 リソースが存在しない (汎用。経路の打ち間違いもここに含める) */
  ResourceNotFound: "4040",
  /** 409 リソースの現在の状態と衝突する (汎用) */
  Conflict: "4090",
  /** 409 メールアドレスが既に使用されている */
  MailAddressAlreadyExists: "4091",
  /** 500 サーバー内部で予期せぬエラーが発生した (汎用) */
  InternalServerError: "5000",
} as const;

export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];
